def test_list_query_count_is_constant(client, django_assert_max_num_queries):
    for i in range(8):
        p = make_product(slug=f"p{i}", variants=(("black", "M", 3), ("white", "L", 2), ("black", "L", 1)))
        ProductImage.objects.create(product=p, image=png_upload(), position=0)
        ProductImage.objects.create(product=p, image=png_upload(), position=1)
    with django_assert_max_num_queries(8):
        res = client.get(LIST)
    assert res.json()["count"] == 8
