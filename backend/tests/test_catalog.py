def test_gender_filter_includes_unisex(client):
    make_product(slug="w", gender="women")
    make_product(slug="m", gender="men")
    make_product(slug="u", gender="unisex")
    assert set(slugs(client.get(LIST, {"gender": "women"}))) == {"w", "u"}
    assert set(slugs(client.get(LIST, {"gender": "men"}))) == {"m", "u"}
    assert client.get(LIST, {"gender": "bogus"}).json()["count"] == 0


