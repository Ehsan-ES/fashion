def test_out_of_stock_variants_do_not_match(client):
    make_product(slug="sold-out", variants=(("black", "M", 0),))
    reserved = make_product(slug="all-reserved", variants=(("black", "M", 2),))
    Inventory.objects.filter(variant__product=reserved).update(reserved=2)
    make_product(slug="ok", variants=(("black", "M", 4),))
    assert slugs(client.get(LIST, {"size": "M"})) == ["ok"]
    assert slugs(client.get(LIST, {"in_stock": "true"})) == ["ok"]
    assert set(slugs(client.get(LIST, {"in_stock": "false"}))) == {"sold-out", "all-reserved"}


