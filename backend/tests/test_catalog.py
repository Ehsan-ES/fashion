def test_webp_conversion_and_resize(settings):
    p = make_product()
    img = ProductImage.objects.create(product=p, image=png_upload(2600, 100))
    assert img.image.name.endswith(".webp")
    img.image.open()
    pil = Image.open(img.image)
    assert pil.format == "WEBP"
    assert max(pil.size) <= 2000


