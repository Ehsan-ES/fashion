def test_facets(client):
    make_product(slug="a", price=1_000_000, variants=(("black", "M", 3),), brand=make_brand("b1", "B1"))
    make_product(slug="b", price=3_000_000, sale_price=2_000_000, variants=(("white", "L", 3),),
                 brand=make_brand("b2", "B2"), gender="men")
    body = client.get(LIST + "filters/").json()
    assert {c["slug"] for c in body["colors"]} == {"black", "white"}
    assert {s["code"] for s in body["sizes"]} == {"M", "L"}
    assert {b["slug"] for b in body["brands"]} == {"b1", "b2"}
    assert body["price"] == {"min": 1000000, "max": 2000000}
    scoped = client.get(LIST + "filters/", {"gender": "men"}).json()
    assert {c["slug"] for c in scoped["colors"]} == {"white"}


