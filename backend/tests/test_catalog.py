def test_detail_has_variants_availability_and_images(client):
    p = make_product(slug="d", variants=(("black", "M", 5), ("black", "L", 0)),
                     material="کتان", model_height_cm=175)
    ProductImage.objects.create(product=p, image=png_upload(), color=make_color("black"), position=0)
    body = client.get(f"{LIST}d/").json()
    assert body["material"] == "کتان"
    assert {v["size"]["code"]: v["available"] for v in body["variants"]} == {"M": 5, "L": 0}
    assert {v["size"]["code"]: v["in_stock"] for v in body["variants"]} == {"M": True, "L": False}
    assert [s["code"] for s in body["sizes"]] == ["M", "L"] or {s["code"] for s in body["sizes"]} == {"M", "L"}
    assert body["images"][0]["url"].startswith("http")
    assert body["images"][0]["color"] == "black"


